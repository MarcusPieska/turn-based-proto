def sum_cols_3_5 (line):
    parts = line.split(":")
    if len(parts) < 6:
        return 0
    return int(parts[3].strip()) + int(parts[4].strip()) + int(parts[5].strip())

def sort_units (units_file):
    print("Sorting %s by sum of columns 3-5" % units_file)
    with open(units_file, "r") as ptr:
        raw_lines = ptr.readlines()
    rows = []
    blanks = []
    for line in raw_lines:
        if line.strip():
            rows.append(line.rstrip("\n"))
        else:
            blanks.append(line)
    rows.sort(key=sum_cols_3_5)
    with open(units_file, "w") as ptr:
        for line in rows:
            ptr.write(line + "\n")
        if blanks:
            ptr.write("\n")
    print("Wrote %u lines to %s" % (len(rows), units_file))

#================================================================================================================================#
#=> - Main -
#================================================================================================================================#

if __name__ == "__main__":
    sort_units("game_config.units")

