void TestHlpCitySpawningValidate::print_summary (const GameState& s, u16 pa, u16 pb) {
    u16 na = 0;
    u16 nb = 0;
    const u16 n = s.m_cities.get_city_count();
    for (u16 i = 0; i < n; ++i) {
        const City* c = s.m_cities.get_city(i);
        if (c == nullptr) {
            continue;
        }
        if (c->get_owner() == pa) {
            na++;
        } else if (c->get_owner() == pb) {
            nb++;
        }
    }
    std::printf("city_spawning: total=%u pa(%u)=%u pb(%u)=%u\n", (u32)n, (u32)pa, (u32)na, (u32)pb, (u32)nb);
}

