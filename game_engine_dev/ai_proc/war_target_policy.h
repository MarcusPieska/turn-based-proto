#ifndef WAR_TARGET_POLICY_H
#define WAR_TARGET_POLICY_H

#include "game_primitives.h"

class GameState;

//================================================================================================================================
//=> - WarTargetPlan -
//================================================================================================================================
//
//  In/out war target bundle: enemy seat plus ordered city indices. Caller may pre-set m_enemy to
//  lock refill to that civ (U16_KEY_NULL = policy may choose). m_n is the valid city count.
//
//================================================================================================================================

struct WarTargetPlan {
    static const u16 k_city_cap = 20u;

    u16 m_enemy; // Target seat; U16_KEY_NULL = unlocked on entry / fail on exit
    u16 m_cities[k_city_cap]; // City indices in attack order
    u16 m_n; // Valid entries in m_cities
};

//================================================================================================================================
//=> - WarTargetKind -
//================================================================================================================================
//
//  Runtime-selected targeting strategy (AI personality can switch per seat later).
//
//================================================================================================================================

enum class WarTargetKind : u8 {
    SecureCapital = 0,
    SectorFlood = 1
};

//================================================================================================================================
//=> - War target entry -
//================================================================================================================================
//
//  war_target_pick dispatches to the active kind. from_* is capital at declare or staging on refill.
//
//================================================================================================================================

void war_target_set_kind (WarTargetKind k);
WarTargetKind war_target_get_kind ();
bool war_target_pick (GameState& st, u16 seat, u16 from_x, u16 from_y, WarTargetPlan* io);

#endif // WAR_TARGET_POLICY_H

