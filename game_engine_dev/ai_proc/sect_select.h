#ifndef SECT_SELECT_H
#define SECT_SELECT_H

#include "game_primitives.h"

//================================================================================================================================
//=> - SectSelectKind -
//================================================================================================================================
//
//  Runtime switch for land-sector target selection. Selection is rare, so a simple enum dispatch
//  is enough. Default is Defensible. City order inside a sector uses CitySelect_Greedy.
//
//================================================================================================================================

enum class SectSelectKind : u8 {
    Defensible = 0,
    Walk = 1
};

void sect_select_set_kind (SectSelectKind k);
SectSelectKind sect_select_get_kind ();

#endif // SECT_SELECT_H

