u16 LuckySeatTurn::fill (const GameState& st, u16* out, u16 cap) {
    if (out == nullptr || cap == 0u || st.m_player_states == nullptr) {
        return 0u;
    }
    u16 n = 0u;
    for (u16 p = 0; p < st.m_player_n; ++p) {
        const PlayerState& ps = st.m_player_states[p];
        if (ps.m_lucky == 0u || ps.m_is_active == 0u) {
            continue;
        }
        if (n >= cap) {
            break;
        }
        out[n++] = p;
    }
    return n;
}

u16 LuckySeatTurn::at (const GameState& st, u32 turn) {
    u16 lucky[k_cap];
    const u16 n = fill(st, lucky, k_cap);
    if (n == 0u) {
        return U16_KEY_NULL;
    }
    return lucky[turn % static_cast<u32>(n)];
}

