bool SettleRules::tile_ok (const GameArraySimple& map, u16 x, u16 y) {
    if (x >= map.width() || y >= map.height()) {
        return false;
    }
    if (!terr_ok(map.get_terrain(x, y))) {
        return false;
    }
    return clim_ok(map.get_climate(x, y), map.get_river(x, y));
}

