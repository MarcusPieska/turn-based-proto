#ifndef DISTRIBUTE_PROPORTIONAL_H
#define DISTRIBUTE_PROPORTIONAL_H

#include "game_primitives.h"

//================================================================================================================================
//=> - DistPropEnt -
//================================================================================================================================
//
//  One populated continent for leftover lucky-seat allocation.
//
//================================================================================================================================

struct DistPropEnt {
    u32 m_tiles; // Continent tile count (proportion weight)
    u16 m_rem; // Starts still free on this continent
};

//================================================================================================================================
//=> - DistributeProportional -
//================================================================================================================================
//
//  Splits quota across continents by tile count; each out[i] is capped by m_rem. Uses largest-remainder
//  rounding, then fills any leftover into continents that still have free seats.
//
//================================================================================================================================

class DistributeProportional {
public:
    static bool run (const DistPropEnt* ents, u16 n, u16 quota, i32* out);

private:
    DistributeProportional () = delete;
};

#endif // DISTRIBUTE_PROPORTIONAL_H

