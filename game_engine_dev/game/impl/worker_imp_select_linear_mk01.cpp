#include "worker_imp_select.h"

//================================================================================================================================
//=> - WorkerImpSelect (mk01) -
//================================================================================================================================

u16 WorkerImpSelect::pick (u16 x, u16 y, u16 job_idx) {
    TileWorkCand cands[32];
    const u16 n = TileWorkAssessor::assess_job(x, y, job_idx, cands, 32);
    for (u16 i = 0; i < n; ++i) {
        if (cands[i].m_imp != U16_KEY_NULL) {
            return cands[i].m_imp;
        }
    }
    return U16_KEY_NULL;
}

