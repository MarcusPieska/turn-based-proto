#ifndef DERIVED_STATICS_IO_H
#define DERIVED_STATICS_IO_H

#include "game_primitives.h"

//================================================================================================================================
//=> - DerivedStaticsIO -
//================================================================================================================================
//
//  Binary read/write of derived map statics (one .bin). Currently the land-sector paint overlay
//  (sector id + 1 per tile). Caller supplies paint for write; GameLoop pulls live sectors.
//
//================================================================================================================================

class DerivedStaticsIO {
public:
    static const u32 k_magic = 0x44525354u; // 'DRST'
    static const u32 k_ver = 1u;

    DerivedStaticsIO () = delete;

    static bool write (cstr path, const u16* paint, u16 w, u16 h, u16 sec_n);
    static bool read (cstr path, u16* w, u16* h, u16* sec_n, u16** paint);
};

#endif // DERIVED_STATICS_IO_H

