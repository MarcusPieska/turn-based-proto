#ifndef LUCKY_SEAT_TURN_H
#define LUCKY_SEAT_TURN_H

#include "game_primitives.h"

class GameState;

//================================================================================================================================
//=> - LuckySeatTurn -
//================================================================================================================================
//
//  Dense 0..N-1 indexing over active lucky seats (seat-index order). fill() writes the seat list;
//  at() returns lucky[turn % N], or U16_KEY_NULL when N is 0.
//
//================================================================================================================================

class LuckySeatTurn {
public:
    static const u16 k_cap = 256u; // Max lucky seats collected in one pass

    static u16 fill (const GameState& st, u16* out, u16 cap);
    static u16 at (const GameState& st, u32 turn);

private:
    LuckySeatTurn () = delete;
};

#endif // LUCKY_SEAT_TURN_H

