#include "negotiate_peace.h"

#include "game_state.h"
#include "log_dbg.h"

//================================================================================================================================
//=> - NegotiatePeace -
//================================================================================================================================

bool NegotiatePeace::deal (GameState& st, u16 a, u16 b) {
    if (st.m_player_states == nullptr || a >= st.m_player_n) {
        return false;
    }
    st.m_player_states[a].m_at_war = 0u;
    LOG_WAR_PEACE::LOG(SC_U32(a), SC_U32(b), SC_U32(st.m_current_turn));
    return true;
}

