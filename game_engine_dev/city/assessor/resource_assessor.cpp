#include "resource_assessor.h"

#include "general_assessor.h"
#include "resource_static_key.h"
#include "runtime_statics.h"

//================================================================================================================================
//=> - ResourceAssessor -
//================================================================================================================================

bool ResourceAssessor::can_extract (u16 res_idx, const AssessorCtx& ctx, const RuntimeStatics& st) {
    if (res_idx >= st.resource().get_item_count()) {
        return false;
    }
    const ResourceStaticDataStruct& row = st.resource().get_item(ResourceStaticDataKey::from_raw(res_idx));
    return GeneralAssessor::chk(row.reqs, ctx);
}

