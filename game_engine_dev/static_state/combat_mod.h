#ifndef COMBAT_MOD_H
#define COMBAT_MOD_H

#include "game_primitives.h"

//================================================================================================================================
//=> - Combat mod limits -
//================================================================================================================================

#define COMBAT_MOD_MAX 8
#define COMBAT_MOD_CITY_DEFENSE U16_KEY_NULL

//================================================================================================================================
//=> - CombatMod -
//================================================================================================================================

typedef struct CombatMod {
    u16 m_role; // Other unit-role idx, or COMBAT_MOD_CITY_DEFENSE
    i16 m_pct;  // Percent change to combat strength
} CombatMod;

//================================================================================================================================
//=> - CombatModList -
//================================================================================================================================

typedef struct CombatModList {
    u8 m_n;
    CombatMod m_mods[COMBAT_MOD_MAX];
} CombatModList;

#endif // COMBAT_MOD_H

